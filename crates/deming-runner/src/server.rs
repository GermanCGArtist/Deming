/// Picks an available ephemeral TCP port on `127.0.0.1` by binding port `0`.
pub fn pick_free_port() -> Result<u16> {
    let listener = TcpListener::bind("127.0.0.1:0")?;
    let port = listener.local_addr()?.port();
    Ok(port)
}

/// Writes `eula.txt` into `server_dir` with `eula=true` (or `false`).
pub fn write_eula(server_dir: &Path, accepted: bool) -> Result<PathBuf> {
    fs::create_dir_all(server_dir)?;
    let path = server_dir.join("eula.txt");
    let content = format!("# Generated by Deming\neula={accepted}\n");
    fs::write(&path, content)?;
    Ok(path)
}

/// Writes `server.properties` into `server_dir` with `online-mode`, `server-port`,
/// and any custom properties sorted deterministically.
pub fn write_server_properties(
    server_dir: &Path,
    port: u16,
    online_mode: bool,
    custom_props: &BTreeMap<String, String>,
) -> Result<PathBuf> {
    fs::create_dir_all(server_dir)?;
    let mut props = custom_props.clone();
    props.insert("online-mode".to_string(), online_mode.to_string());
    props.insert("server-port".to_string(), port.to_string());

    let mut content = String::from("# Generated by Deming\n");
    for (key, value) in &props {
        content.push_str(&format!("{key}={value}\n"));
    }

    let path = server_dir.join("server.properties");
    fs::write(&path, content)?;
    Ok(path)
}

/// Configuration required to launch a local dedicated server process.
#[derive(Debug, Clone)]
pub struct ServerLaunchConfig {
    /// Run ID for emitted [`RunEvent`]s.
    pub run_id: Uuid,
    /// Path to the `java` executable (or custom executable when testing).
    pub java_exe: PathBuf,
    /// Working directory for the server (`eula.txt` and `server.properties` are written here).
    pub server_dir: PathBuf,
    /// Optional path to the server `.jar` (launches with `-jar <server_jar>` when set).
    pub server_jar: Option<PathBuf>,
    /// Extra JVM arguments placed before `-jar`.
    pub jvm_args: Vec<String>,
    /// Extra program arguments placed after `-jar <jar>` (e.g., `["nogui"]`).
    pub program_args: Vec<String>,
    /// Server specification from the job.
    pub spec: ServerSpec,
    /// Allocated RAM in MiB (`-Xmx{ram_mb}M`).
    pub ram_mb: u64,
    /// Optional CPU core affinity limit.
    pub cpu_cores: Option<usize>,
    /// OS process scheduling priority.
    pub priority: ProcessPriority,
    /// Maximum seconds to wait for `ready_pattern` before failing startup.
    pub startup_timeout_secs: u64,
}

impl ServerLaunchConfig {
    /// Builds the argument list passed to `java_exe`, resolving relative JAR/classpath paths
    /// to absolute paths so `current_dir` in `server_dir` never breaks relative references.
    pub fn build_args(&self) -> Vec<String> {
        let mut args = Vec::new();
        let resolved_jvm = absolutize_classpath_in_args(&self.jvm_args);
        if let Some(jar) = &self.server_jar {
            if self.ram_mb > 0 {
                let xms = self.ram_mb.min(512).max(128.min(self.ram_mb));
                args.push(format!("-Xms{xms}M"));
                args.push(format!("-Xmx{}M", self.ram_mb));
            }
            args.extend(resolved_jvm);
            args.push("-jar".to_string());
            args.push(absolutize_path(jar).to_string_lossy().into_owned());
            if self.program_args.is_empty() {
                args.push("nogui".to_string());
            } else {
                args.extend(self.program_args.iter().cloned());
            }
        } else {
            args.extend(resolved_jvm);
            args.extend(self.program_args.iter().cloned());
        }
        args
    }
}

fn absolutize_classpath_in_args(args: &[String]) -> Vec<String> {
    let sep = if cfg!(windows) { ';' } else { ':' };
    let mut out = Vec::with_capacity(args.len());
    let mut next_is_cp = false;
    for arg in args {
        if next_is_cp {
            next_is_cp = false;
            let joined = arg
                .split(sep)
                .filter(|s| !s.is_empty())
                .map(|entry| absolutize_path(Path::new(entry)).to_string_lossy().into_owned())
                .collect::<Vec<_>>()
                .join(&sep.to_string());
            out.push(joined);
            continue;
        }
        if arg == "-cp" || arg == "-classpath" {
            next_is_cp = true;
        }
        out.push(arg.clone());
    }
    out
}

/// Handle to a running dedicated server process contained inside a [`JobHandle`].
pub struct ServerProcess {
    port: u16,
    job: Arc<JobHandle>,
    child: Child,
    stdin: Option<ChildStdin>,
    logs: Arc<Mutex<Vec<String>>>,
    tail_tasks: Vec<JoinHandle<()>>,
}

impl ServerProcess {
    /// Writes `eula.txt` and `server.properties`, spawns the server inside a Job Object,
    /// tails stdout/stderr, and waits until `spec.ready_pattern` is matched.
    pub async fn start(
        config: ServerLaunchConfig,
        abort: &AbortHandle,
        events: Option<mpsc::UnboundedSender<RunEvent>>,
    ) -> Result<Self> {
        if abort.is_aborted() {
            return Err(DemingError::Process(
                "server launch skipped because run is aborted".to_string(),
            ));
        }

        let ready_regex = Regex::new(&config.spec.ready_pattern).map_err(|e| {
            DemingError::InvalidSpec(format!(
                "invalid server ready_pattern '{}': {e}",
                config.spec.ready_pattern
            ))
        })?;

        let port = match config.spec.port {
            Some(p) if p > 0 => p,
            _ => pick_free_port()?,
        };

        let server_dir = absolutize_path(&config.server_dir);
        let java_exe = absolutize_executable(&config.java_exe);

        fs::create_dir_all(&server_dir)?;
        write_eula(&server_dir, true)?;
        write_server_properties(
            &server_dir,
            port,
            config.spec.online_mode,
            &config.spec.server_properties,
        )?;

        let job = Arc::new(JobHandle::new()?);
        abort.register_job(Arc::clone(&job))?;

        let args = config.build_args();
        let mut cmd = Command::new(&java_exe);
        cmd.args(&args)
            .current_dir(&server_dir)
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped());

        #[cfg(windows)]
        {
            const CREATE_NO_WINDOW: u32 = 0x0800_0000;
            cmd.creation_flags(CREATE_NO_WINDOW);
        }

        let mut child = cmd.spawn().map_err(|e| {
            DemingError::Process(format!(
                "failed to spawn server '{}': {e}",
                config.java_exe.display()
            ))
        })?;

        if let Err(err) = job.assign_tokio_child(&child) {
            let _ = child.start_kill();
            let _ = job.terminate_all();
            return Err(err);
        }

        if let Err(err) = configure_tokio_child(&child, config.cpu_cores, config.priority) {
            let _ = job.terminate_all();
            return Err(err);
        }

        let stdin = child.stdin.take();
        let stdout = child.stdout.take();
        let stderr = child.stderr.take();

        let logs = Arc::new(Mutex::new(Vec::new()));
        let (ready_tx, ready_rx) = oneshot::channel::<()>();
        let ready_tx = Arc::new(Mutex::new(Some(ready_tx)));

        let mut tail_tasks = Vec::new();

        if let Some(out) = stdout {
            let logs_ref = Arc::clone(&logs);
            let events_ref = events.clone();
            let regex_ref = ready_regex.clone();
            let ready_ref = Arc::clone(&ready_tx);
            let run_id = config.run_id;
            tail_tasks.push(tokio::spawn(async move {
                let mut lines = BufReader::new(out).lines();
                while let Ok(Some(line)) = lines.next_line().await {
                    if regex_ref.is_match(&line) {
                        if let Ok(mut guard) = ready_ref.lock() {
                            if let Some(tx) = guard.take() {
                                let _ = tx.send(());
                            }
                        }
                    }
                    if let Ok(mut buf) = logs_ref.lock() {
                        buf.push(line.clone());
                    }
                    if let Some(tx) = &events_ref {
                        let _ = tx.send(RunEvent::LogLine {
                            run_id,
                            source: "server".to_string(),
                            line,
                            timestamp: Utc::now(),
                        });
                    }
                }
            }));
        }

        if let Some(err_stream) = stderr {
            let logs_ref = Arc::clone(&logs);
            let events_ref = events.clone();
            let regex_ref = ready_regex;
            let ready_ref = Arc::clone(&ready_tx);
            let run_id = config.run_id;
            tail_tasks.push(tokio::spawn(async move {
                let mut lines = BufReader::new(err_stream).lines();
                while let Ok(Some(line)) = lines.next_line().await {
                    if regex_ref.is_match(&line) {
                        if let Ok(mut guard) = ready_ref.lock() {
                            if let Some(tx) = guard.take() {
                                let _ = tx.send(());
                            }
                        }
                    }
                    if let Ok(mut buf) = logs_ref.lock() {
                        buf.push(line.clone());
                    }
                    if let Some(tx) = &events_ref {
                        let _ = tx.send(RunEvent::LogLine {
                            run_id,
                            source: "server".to_string(),
                            line,
                            timestamp: Utc::now(),
                        });
                    }
                }
            }));
        }

        let timeout_dur = Duration::from_secs(config.startup_timeout_secs.max(1));
        let sleep = tokio::time::sleep(timeout_dur);
        tokio::pin!(sleep);
        tokio::pin!(ready_rx);

        tokio::select! {
            res = &mut ready_rx => {
                match res {
                    Ok(()) => {
                        if let Some(tx) = &events {
                            let _ = tx.send(RunEvent::ServerReady {
                                run_id: config.run_id,
                                port,
                                timestamp: Utc::now(),
                            });
                        }
                        Ok(Self {
                            port,
                            job,
                            child,
                            stdin,
                            logs,
                            tail_tasks,
                        })
                    }
                    Err(_) => {
                        let _ = job.terminate_all();
                        let _ = child.wait().await;
                        Err(DemingError::Process(
                            "server output closed before ready_pattern matched".to_string(),
                        ))
                    }
                }
            }
            status = child.wait() => {
                let _ = job.terminate_all();
                let code = status.ok().and_then(|s| s.code());
                Err(DemingError::Process(format!(
                    "server exited prematurely before becoming ready (exit code: {code:?})"
                )))
            }
            _ = abort.cancelled() => {
                let _ = job.terminate_all();
                let _ = child.wait().await;
                Err(DemingError::Process("server startup aborted".to_string()))
            }
            _ = &mut sleep => {
                let _ = job.terminate_all();
                let _ = child.wait().await;
                Err(DemingError::Timeout {
                    operation: "server startup".to_string(),
                    seconds: config.startup_timeout_secs,
                })
            }
        }
    }

    /// TCP port bound for this server.
    pub fn port(&self) -> u16 {
        self.port
    }

    /// OS process ID of the server process, if still running.
    pub fn pid(&self) -> Option<u32> {
        self.child.id()
    }

    /// Snapshot of captured stdout/stderr lines so far.
    pub fn logs(&self) -> Vec<String> {
        self.logs.lock().map(|g| g.clone()).unwrap_or_default()
    }

    /// Reference to the underlying [`JobHandle`].
    pub fn job(&self) -> &Arc<JobHandle> {
        &self.job
    }

    /// Attempts a graceful `"stop"` command over stdin, then force-terminates the Job Object
    /// if the server does not exit within `graceful_timeout`.
    pub async fn shutdown(&mut self, graceful_timeout: Duration) -> Result<Option<i32>> {
        if let Some(stdin) = self.stdin.as_mut() {
            let _ = stdin.write_all(b"stop\n").await;
            let _ = stdin.flush().await;
        }
        self.stdin.take();

        let code = match tokio::time::timeout(graceful_timeout, self.child.wait()).await {
            Ok(Ok(status)) => status.code(),
            Ok(Err(e)) => {
                let _ = self.job.terminate_all();
                return Err(DemingError::Io(e));
            }
            Err(_) => {
                let _ = self.job.terminate_all();
                let status = self.child.wait().await?;
                status.code()
            }
        };

        for task in self.tail_tasks.drain(..) {
            let _ = task.await;
        }
        Ok(code)
    }

    /// Immediately terminates the server process tree via its Job Object.
    pub async fn kill(&mut self) -> Result<()> {
        self.stdin.take();
        self.job.terminate_all()?;
        let _ = self.child.wait().await;
        for task in self.tail_tasks.drain(..) {
            let _ = task.await;
        }
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use deming_core::ModLoader;

    #[test]
    fn server_build_args_absolutizes_relative_jar_and_classpath() {
        let cfg_jar = ServerLaunchConfig {
            run_id: Uuid::new_v4(),
            java_exe: PathBuf::from(".deming-test/ws/cache/jre/bin/java.exe"),
            server_dir: PathBuf::from(".deming-test/ws/servers/run1"),
            server_jar: Some(PathBuf::from(".deming-test/ws/cache/loaders/fabric/server.jar")),
            jvm_args: vec![],
            program_args: vec![],
            spec: ServerSpec {
                mc_version: "1.20.1".to_string(),
                loader: ModLoader::Fabric,
                loader_version: None,
                mods: vec![],
                online_mode: false,
                port: None,
                server_properties: BTreeMap::new(),
                ready_pattern: "Done".to_string(),
                auto_connect_clients: true,
                ram_mb: Some(1024),
            },
            ram_mb: 1024,
            cpu_cores: None,
            priority: ProcessPriority::Normal,
            startup_timeout_secs: 30,
        };

        let jar_args = cfg_jar.build_args();
        let jar_idx = jar_args.iter().position(|a| a == "-jar").unwrap();
        assert!(
            Path::new(&jar_args[jar_idx + 1]).is_absolute(),
            "expected absolute -jar path, got {}",
            jar_args[jar_idx + 1]
        );
        assert!(absolutize_executable(&cfg_jar.java_exe).is_absolute());

        let sep = if cfg!(windows) { ";" } else { ":" };
        let cfg_cp = ServerLaunchConfig {
            server_jar: None,
            jvm_args: vec![
                "-cp".to_string(),
                format!(".deming-test/ws/cache/a.jar{sep}.deming-test/ws/cache/b.jar"),
            ],
            ..cfg_jar
        };
        let cp_args = cfg_cp.build_args();
        let cp_idx = cp_args.iter().position(|a| a == "-cp").unwrap();
        for entry in cp_args[cp_idx + 1].split(sep.chars().next().unwrap()) {
            assert!(Path::new(entry).is_absolute(), "expected absolute cp entry: {entry}");
        }
    }
}
